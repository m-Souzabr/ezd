// Writes docs/RULES.md from the rule registry: each rule's id, severity and description
// (the doc comment above its `defineRule`), in the order `validate` runs them, with the
// thresholds from rules/constants.ts that it uses. Run through `pnpm --filter @ezd/core
// schema`; CI fails when the file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const rulesDir = join(root, 'src', 'rules', 'rules');
const read = (path) => readFileSync(path, 'utf8');
const prose = (comment) =>
  comment
    .split('\n')
    .map((line) => line.replace(/^\s*\*\s?/, '').trim())
    .filter(Boolean)
    .join(' ');

// Thresholds: name, value in inches, and the comment above them (or above their group).
const constants = read(join(root, 'src', 'rules', 'constants.ts'));
const thresholds = new Map();
let lastComment = '';
for (const line of constants.split('\n')) {
  const doc = /\/\*\*(.*)\*\//.exec(line);
  if (doc) lastComment = doc[1].trim();
  const value = /export const (\w+): Len = inches\(([\d.]+)\);/.exec(line);
  if (value) thresholds.set(value[1], { inches: value[2], about: lastComment });
  if (line.trim() === '') lastComment = '';
}

// The registry order, from rules/index.ts.
const index = read(join(rulesDir, 'index.ts'));
const files = new Map(
  [...index.matchAll(/import \{ (\w+) \} from '\.\/([\w-]+)\.js';/g)].map((m) => [m[1], m[2]]),
);
const order = /RULES: readonly Rule\[\] = \[([\s\S]*?)\];/.exec(index)[1].match(/\w+/g);

const rows = order.map((name) => {
  const source = read(join(rulesDir, `${files.get(name)}.ts`));
  const rule = /export const \w+ = defineRule\(\s*'([^']+)',\s*'(\w+)'/.exec(source);
  if (!rule) throw new Error(`No defineRule in ${files.get(name)}.ts`);
  // The doc comment right above the rule.
  const before = source.slice(0, rule.index);
  const start = before.lastIndexOf('/**');
  const comment = /\/\*\*([\s\S]*?)\*\/\s*$/.exec(before.slice(start));
  if (start === -1 || !comment)
    throw new Error(`No doc comment above the rule in ${files.get(name)}.ts`);
  const used = [...thresholds.keys()].filter((key) => new RegExp(`\\b${key}\\b`).test(source));
  return { id: rule[1], severity: rule[2], about: prose(comment[1]), used };
});

const lines = [
  '# Design rules',
  '',
  '<!-- Generated by packages/core/scripts/write-rules-doc.mjs. Do not edit by hand. -->',
  '',
  '`validate(doc, catalog)` runs these rules, in this order. A rule never blocks a command;',
  'the editor shows errors and warnings next to the design. They are design-quality',
  "guidance, not building-code compliance: check local codes and the manufacturer's",
  'instructions before building.',
  '',
  '| Rule | Severity | What it checks | Thresholds |',
  '| --- | --- | --- | --- |',
  ...rows.map(
    (row) =>
      `| \`${row.id}\` | ${row.severity} | ${row.about.replace(/\|/g, '\\|')} | ${
        row.used.map((key) => `\`${key}\` ${thresholds.get(key).inches}"`).join(', ') || '—'
      } |`,
  ),
  '',
  '## Thresholds',
  '',
  'From `packages/core/src/rules/constants.ts`.',
  '',
  '| Name | Value | Meaning |',
  '| --- | --- | --- |',
  ...[...thresholds].map(([key, t]) => `| \`${key}\` | ${t.inches}" | ${t.about} |`),
  '',
];
writeFileSync(resolve(root, '..', '..', 'docs', 'RULES.md'), lines.join('\n'));
console.log('wrote docs/RULES.md');
