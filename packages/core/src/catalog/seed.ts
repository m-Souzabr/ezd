/** Every multiple of 3 in from `min` to `max`, both in inches. */
const stepped = (min: number, max: number): WidthRule => ({
  min: inches(min),
  max: inches(max),
  step: STEP,
});
const oneOf = (...widths: number[]): WidthRule => ({ values: widths.map(inches) });
const fillerWidth: WidthRule = { free: { min: FILLER_MIN_WIDTH, max: FILLER_MAX_WIDTH } };
const lens = (...values: number[]): Len[] => values.map(inches);
const size = (width: number, height: number, depth: number): CatalogEntry['defaultSize'] => ({
  width: inches(width),
  height: inches(height),
  depth: inches(depth),
});

const doors = (...values: number[]): OptionDef => ({
  key: 'doors',
  type: 'int',
  values,
  default: values.at(-1)!,
});
const hinge: OptionDef = { key: 'hinge', type: 'enum', values: ['left', 'right'], default: 'left' };

const price = (
  baseCents: number,
  perInchWidthCents: number,
  optionCents?: Record<string, number>,
): CatalogEntry['price'] => ({
  baseCents,
  perInchWidthCents,
  ...(optionCents && { optionCents }),
});

