@cache
def _tools_file() -> dict[str, Any]:
    return json.loads(Path(settings.LLM_TOOLS_SCHEMA_PATH).read_text(encoding="utf-8"))


@cache
def catalog_index() -> str:
    return Path(settings.LLM_CATALOG_INDEX_PATH).read_text(encoding="utf-8").strip()


@cache
def tools() -> list[ToolDefinition]:
    return [
        ToolDefinition(name=t["name"], description=t["description"], parameters=t["parameters"])
        for t in _tools_file()["tools"]
    ]


@cache
def _validators() -> dict[str, Draft202012Validator]:
    return {tool.name: Draft202012Validator(tool.parameters) for tool in tools()}


@dataclass(frozen=True)
class CheckedCall:
    name: str
    arguments: dict[str, Any]


def _describe(error: Any) -> str:
    path = ".".join(str(part) for part in error.absolute_path)
    return f"{path}: {error.message}" if path else error.message


def _problem(validator: Draft202012Validator, arguments: dict[str, Any]) -> str | None:
    """What is wrong with the arguments, or None.

    `add_item` is one schema per catalog entry. Its errors are those of the entry the call
    names, not of every entry it does not.
    """
    errors = list(validator.iter_errors(arguments))
    if not errors:
        return None
    for error in errors:
        if error.validator != "oneOf" or error.absolute_path:
            continue
        catalog_id = arguments.get("catalogId")
        variant = next(
            (
                schema
                for schema in error.validator_value
                if schema.get("properties", {}).get("catalogId", {}).get("const") == catalog_id
            ),
            None,
        )
        if variant is None:
            return f"catalogId: {catalog_id!r} is not in the catalog. Use an id from the catalog."
        defs = validator.schema.get("$defs", {})
        found = best_match(Draft202012Validator({**variant, "$defs": defs}).iter_errors(arguments))
        return _describe(found) if found is not None else None
    return _describe(best_match(errors))


def check_tool_calls(calls: list[ToolCall]) -> tuple[list[CheckedCall], list[str]]:
    """Each call parsed and checked against its tool's JSON Schema, or the reasons it is not.

    Any malformed call makes the whole proposal malformed, so the errors cover every call.
    """
    validators = _validators()
    checked: list[CheckedCall] = []
    errors: list[str] = []
    for index, call in enumerate(calls):
        where = f"Tool call {index + 1} ({call.name})"
        validator = validators.get(call.name)
        if validator is None:
            errors.append(f"{where}: there is no such tool. Use one of {', '.join(validators)}.")
            continue
        try:
            arguments = json.loads(call.arguments)
        except ValueError:
            errors.append(f"{where}: the arguments are not valid JSON.")
            continue
        if not isinstance(arguments, dict):
            errors.append(f"{where}: the arguments must be a JSON object.")
            continue
        problem = _problem(validator, arguments)
        if problem is not None:
            errors.append(f"{where}: {problem[:300]}")
            continue
        checked.append(CheckedCall(name=call.name, arguments=arguments))
    return checked, errors
