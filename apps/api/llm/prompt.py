"""The prompt and the tools, and the check of every tool call the model makes.

The tools and the catalog index are generated by core into packages/core/schema/
(`pnpm --filter @ezd/core schema`), so the server sends the model exactly what core
converts and validates.
"""

import json
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any

from django.conf import settings
from jsonschema import Draft202012Validator
from jsonschema.exceptions import best_match

from .client import ToolCall, ToolDefinition

